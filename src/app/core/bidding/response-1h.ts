// src/app/core/bidding/response-1h.ts
import { Bid, Card, CheckResult, HandInfo, SUITS, SUIT_SYMBOLS, Suit, describeBid } from './types';
import { isGoodFive, sameBid } from './common';

function resp4Plus(p: number, L: Record<Suit, number>): Bid {
    // Решение №15: блок с 0 РС требует синглета или ренонса
    // в какой-то из мастей. Иначе — пас: блок без укрытия
    // ничего не даёт, только съедает место.
    if (p === 0) {
        const hasShort = SUITS.some(s => L[s] <= 1);
        if (!hasShort) return { type: 'PASS' };
    }
    // Решение №9: 0-5 РС — блок от длины фита: блок — это длина, а не сила.
    // Проверка «хороших пяти» здесь не нужна, она касается только ветки «ровно 3 червы».
    if (p <= 5) {
        return L.H >= 5
        ? { type: 'SUIT', level: 4, suit: 'H' }
        : { type: 'SUIT', level: 3, suit: 'H' };
    }
    // 6-9 РС — простой подъём 2♥ NF.
    if (p <= 9) return { type: 'SUIT', level: 2, suit: 'H' };
    // 10+ РС (решение №5, №7): сила и фит одной заявкой
    return { type: 'NT', level: 2 };
}

function resp3(p: number, L: Record<Suit, number>, cards: Card[]): Bid {
    if (p <= 4) return { type: 'PASS' };
    if (p === 5) {
        return isGoodFive(cards, 'H')
        ? { type: 'SUIT', level: 2, suit: 'H' }
        : { type: 'PASS' };
    }
    if (p <= 9) return { type: 'SUIT', level: 2, suit: 'H' }; // решение №1
    // 10+ РС (решение №2)
    if (L.S >= 4) return { type: 'SUIT', level: 1, suit: 'S' };
    // Решение №13: обе минорки длинные — выбор по длине и старшинству.
    // 4-4 → трефа (ближайшая, дешевле), 5-5 → бубна (старшая),
    // перевес длины → более длинная.
    if (L.C >= 4 && L.D >= 4) {
        if (L.C === L.D) {
            return L.C >= 5
            ? { type: 'SUIT', level: 2, suit: 'D' }
            : { type: 'SUIT', level: 2, suit: 'C' };
        }
        return L.D > L.C
        ? { type: 'SUIT', level: 2, suit: 'D' }
        : { type: 'SUIT', level: 2, suit: 'C' };
    }
    if (L.C >= 4) return { type: 'SUIT', level: 2, suit: 'C' };
    if (L.D >= 4) return { type: 'SUIT', level: 2, suit: 'D' };
    // С 3 червями и ≤3 пиками на минорки приходится ≥7 карт, ветка
    // недостижима — оставлена страховкой на случай правок генератора.
    return { type: 'SUIT', level: 3, suit: 'H' };
}

function respNoFit(p: number, L: Record<Suit, number>, cards: Card[]): Bid {
    // Решение №14: одномастная пика (6+ карт) — своя ветка, ДО правила №12.
    // 0-11 РС → 1♠ FR, 12+ РС → 2♠ FG (форс к гейму: шлем/гейм
    // ищем сами, торговлю не отпускаем). Меньше 5 РС — пас.
    if (L.S >= 6) {
        if (p >= 12) return { type: 'SUIT', level: 2, suit: 'S' };
        if (p >= 5) return { type: 'SUIT', level: 1, suit: 'S' };
        // p <= 4 проваливается в пас ниже.
    }
    // Решение №12: 4+ пики и от 5 РС — 1♠, качество очков не оцениваем
    // («берём как есть»). Проверка стоит ДО гейта «хороших пяти»:
    // пика при ровно 5 РС отвечает и с «плохой» пятёркой.
    if (p >= 5 && L.S >= 4) return { type: 'SUIT', level: 1, suit: 'S' };
    if (p <= 4) return { type: 'PASS' };
    if (p === 5 && !isGoodFive(cards, null)) return { type: 'PASS' };
    // Хорошие пять играем как шесть и проваливаемся дальше.
    // Решение №6: 6-10 РС без фита и без 4 пик — 1БК.
    if (p <= 10) return { type: 'NT', level: 1 };

    // 11+ РС (решение №11). Здесь червы ≤2, пики ≤3 → на минорки
    // приходится ≥8 карт. Равномерность по схеме: 4-3-3-3, 4-4-3-2,
    // 5-3-3-2 (пятёрка — в минорке, потому что пики ≤3 и червы ≤2).
    const lens = [L.S, L.H, L.D, L.C].sort((a, b) => b - a);
    const balanced = ['4333', '4432', '5332'].includes(lens.join(''));

    if (balanced) {
        if (p >= 13 && p <= 15) return { type: 'NT', level: 3 };
        // 11-12 или 16+ → 2♣/2♦ FR: обещает от 4-ки, пятёрка — только в 5-3-3-2.
        if (L.C === 5) return { type: 'SUIT', level: 2, suit: 'C' };
        if (L.D === 5) return { type: 'SUIT', level: 2, suit: 'D' };
        return { type: 'SUIT', level: 2, suit: 'C' }; // 4-4 минорки → ближайшая (решение №10)
    }
    // Не равномерная: 5-4, 5-5 или 6+ в минорках. Называем самую
    // длинную; при равенстве от 5-ки начинаем со старшей — бубна.
    const minor: Suit = L.D >= L.C ? 'D' : 'C';
    return { type: 'SUIT', level: 2, suit: minor };
}

export function expectedResponse1H(h: HandInfo): Bid {
    const L = h.lengths;
    if (L.H >= 4) return resp4Plus(h.points, L);
    if (L.H === 3) return resp3(h.points, L, h.cards ?? []);
    return respNoFit(h.points, L, h.cards ?? []);
}

function explainResponse1H(h: HandInfo): string {
    const L = h.lengths;
    const p = h.points;
    const labels: Record<Suit, string> = { C: '♣', D: '♦', H: '♥', S: '♠' };

    if (L.H >= 4) {
        // Решение №15: нулевая рука блокует только с синглетом/ренонсом.
        if (p === 0) {
            const hasShort = SUITS.some(s => L[s] <= 1);
            if (!hasShort) {
                return `0 РС и четыре+ червы, но ровный расклад без синглета и ренонса — пас: блок без укрытия не имеет защитной ценности.`;
            }
            return `0 РС и четыре+ червы — блок от длины фита: расклад с укрытием (${L.H >= 5 ? '4♥' : '3♥'}) позволяет мешать противникам даже без очков.`;
        }
        // 0-5 РС — блок от длины фита (решение №9): блок — это длина, а не сила.
        // Проверка «хороших пяти» здесь не нужна, она касается только ветки «ровно 3 червы».
        if (p <= 5) {
            return L.H >= 5
            ? `${p} РС и 5+ червей — блок 4♥ от длины фита: на силу не претендуем, но длиной тесним торговлю противников.`
            : `${p} РС и четыре червы — блок 3♥ от длины фита: мешаем противникам, силы на большее нет.`;
        }
        if (p <= 9) return `4+ червей и 6–9 РС — простой подъём 2♥, не форсирующий.`;

        // 10+ РС и 4+ червей — 2БК (решение №5, №7). Оговорка про пики — только если пиков 4+.
        let msg = `10+ РС и 4+ червей — 2БК: сила и фит одной заявкой.`;
        if (L.S >= 4) {
            msg += ` Пиковая четвёрка молчит до следующего круга; открывающий ответит 3♥ (инвайт не принят) или 4♥ (принят).`;
        }
        return msg;
    }

    if (L.H === 3) {
        if (p <= 4) return `Три червы, ${p} РС — пас.`;
        if (p === 5) {
            return isGoodFive(h.cards ?? [], 'H')
            ? `Три червы и пять «хороших» РС — играем как шесть: 2♥.`
            : `Три червы и пять «плохих» РС — пас.`;
        }
        if (p <= 9) {
            const base = `Три червы и 6–9 РС — обязательный подъём 2♥`;
            return L.S >= 4
            ? `${base}: фит важнее пиковой четвёрки, пику партнёр назовёт сам.`
            : `${base}.`;
        }
        if (L.S >= 4) return `Три червы, 10+ РС и четыре пики — 1♠: старшая четвёрка на первом уровне, фит покажем третьим или четвёртым кругом.`;
        if (L.C >= 4 && L.D >= 4) {
            const m = L.C === L.D
            ? (L.C >= 5 ? '♦ (5-5 — старшая минорка)' : '♣ (4-4 — ближайшая, дешевле)')
            : L.D > L.C ? '♦ (более длинная)' : '♣ (более длинная)';
            return `Три червы, 10+ РС, обе минорки 4+ — 2${m}.`;
        }
        if (L.C >= 4) return `Три червы, 10+ РС — ближайшая боковая четвёрка: 2♣.`;
        if (L.D >= 4) return `Три червы, 10+ РС — ближайшая боковая четвёрка: 2♦.`;
        return `Три червы, 10+ РС — запасной вариант 3♥ (ветка практически недостижима).`;
    }

    // без фита
    // Решение №14: одномастная пика (6+) — своя ветка, ДО правила №12.
    if (L.S >= 6) {
        if (p >= 12) return `Одномастная пика (6+ карт), ${p} РС — 2♠ FG: форс к гейму. Шесть карт — это уже не «четвёрка как есть», а сила, с которой торговлю не отпускаем.`;
        if (p >= 5) return `Одномастная пика (6+ карт), ${p} РС — 1♠ FR: силу покажем следующим кругом, если она есть.`;
        return `Одномастная пика, но меньше 5 РС — пас.`;
    }
    // Решение №12: 4+ пики и от 5 РС — 1♠, качество очков не оцениваем.
    if (p >= 5 && L.S >= 4) {
        return p === 5
        ? `Без фита, четыре пики и 5 РС — 1♠: качество очков не оцениваем, берём как есть. Меньше 5 РС был бы пас.`
        : `Без фита и четыре пики — всегда 1♠: старшая четвёрка на первом уровне.`;
    }
    if (p <= 4) return `Без фита, ${p} РС — пас.`;
    if (p === 5 && !isGoodFive(h.cards ?? [], null)) return `Без фита, пять «плохих» РС — пас.`;
    // Хорошие пять играем как шесть и проваливаемся дальше.
    // Решение №6: граница 1БК — 10 РС включительно.
    if (p <= 10) return `Без фита, 6–10 РС — 1БК, не форсирующий. Руки от 11 РС идут в дерево ниже.`;

    // Решение №11: равномерность по схемным паттернам, не «нет масти длиннее 4».
    const lens = [L.S, L.H, L.D, L.C].sort((a, b) => b - a);
    const balanced = ['4333', '4432', '5332'].includes(lens.join(''));

    if (balanced) {
        return p >= 13 && p <= 15
        ? `Равномерная, 13–15 РС — 3БК: гейм и точка. Шлем не ищем; открывающий может переставить в 4♥, если располагает его рука.`
        : `Равномерная, ${p} РС — 2 ${L.C === 5 ? '♣' : L.D === 5 ? '♦' : '♣'} FR: обещает от 4-ки в названной масти, пятёрка — только при раскладе 5-3-3-2. Ищем шлем — место в торговле сохраняем.`;
    }
    const minor: Suit = L.D >= L.C ? 'D' : 'C';
    return `Не равномерная, ${p} РС — 2 ${labels[minor]} FR: называем самую длинную масть, от 5-ки — со старшей.`;
}

/**
 * Проверка ответа на 1♥ — зеркально checkBid для открытий,
 * чтобы страница ответов жила по той же схеме UI.
 */
export function checkResponse1H(h: HandInfo, bid: Bid): CheckResult {
    const expected = expectedResponse1H(h);
    if (sameBid(bid, expected)) {
        return { ok: true, expected, message: `Заявка соответствует схеме! ${h.points} РС. ${explainResponse1H(h)}` };
    }
    return {
        ok: false,
        expected,
        message: `По схеме здесь: ${describeBid(expected)}. ${explainResponse1H(h)}`
    };
}

/** Открывающий должен иметь право на 1♥: 11–21 РС, 5+ червей, ≤4 пики. */
export function canOpen1H(h: HandInfo): boolean {
    return h.points >= 11 && h.points <= 21 && h.lengths.H >= 5 && h.lengths.S <= 4;
}
